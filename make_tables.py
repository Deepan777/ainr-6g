def tab_broad():
    """Broadly trained DiscNRX vs the narrowly trained DiscNRX (seed 0) on identical slots."""
    S = read(os.path.join(DATA, "broad_summary.csv"))
    if not S:
        return False
    get = {(r["cond"], float(r["snr_db"])): r for r in S}
    conds = [("S1", "S1 (matched)"), ("DS600", "DS\\,600"), ("DS1000", "DS\\,1000"), ("CDLA", "CDL-A"),
             ("CDLD", "CDL-D"), ("S2", "S2"), ("V90", "90\\,km/h"), ("V150", "150\\,km/h"),
             ("V250", "250\\,km/h"), ("V400", "400\\,km/h")]

    def auc_cell(r, k):
        return "--" if r is None or r.get(k) in (None, "") else f3(r[k])

