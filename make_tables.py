"""Generate the LaTeX results tables of the manuscript from FINAL_OJCOMS/data/*.csv.

Every number in a table comes from the analysis outputs; tables whose experiments
have not finished are emitted with a visible \\pending marker instead of numbers.

Usage: python make_tables.py        (run after analyze_results.py)
"""
import csv
import math
import os
from collections import defaultdict

ROOT = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(ROOT, "FINAL_OJCOMS", "data")
RES = os.path.join(ROOT, "results", "ojcoms")
OUT = os.path.join(ROOT, "FINAL_OJCOMS", "tables")
os.makedirs(OUT, exist_ok=True)


def read(p):
    if not os.path.exists(p):
        return []
    with open(p, newline="") as f:
        return list(csv.DictReader(f))


def seeds_word(n):
    """'Seed' or 'Seeds' for a caption, from the actual seed count (n may be a string)."""
    try:
        return "Seed" if int(float(n)) == 1 else "Seeds"
    except (TypeError, ValueError):
        return "Seeds"


def f3(x):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "--"
    return "--" if v != v else f"{v:.3f}"


def write(name, text):
    with open(os.path.join(OUT, name) + ".tmp", "w", encoding="utf-8") as f:
        f.write("% Auto-generated by make_tables.py from FINAL_OJCOMS/data -- do not edit by hand.\n" + text)
    os.replace(os.path.join(OUT, name) + ".tmp", os.path.join(OUT, name))
    print(f"  -> FINAL_OJCOMS/tables/{name}")


# ------------------------------------------------------------------ Table: drift detection
def tab_detection():
    A = read(os.path.join(DATA, "detector_auc_summary.csv"))
    R = read(os.path.join(DATA, "detector_relevance.csv"))
    if not A:
        return
    conds = [("DS600", "DS\\,600"), ("DS1000", "DS\\,1000"), ("S2", "S2"), ("CDLD", "CDL-D"),
             ("V90", "90\\,km/h"), ("V250", "250\\,km/h"), ("V400", "400\\,km/h")]
    stats = [("resid", "Residual $\\mathcal{E}$"), ("tdisp", "Temporal disp.\\ $\\mathcal{D}$"),
             ("comb", "Combined"), ("conf_a", "Confidence, AINR"), ("conf_d", "Confidence, DiscNRX"),
             ("crcfail_d", "CRC failure, DiscNRX"), ("cf", "Pilot freq.\\ corr.\\ $|z|$"),
             ("ymag", "Mean $|Y|$ $|z|$")]
    get = {(r["snr_db"], r["window"], r["stat"], r["cond"]): r for r in A}
    rho = defaultdict(list)
    for r in R:
        if r["snr_db"] == "5.0" and r["spearman_rho"] not in ("", "nan"):
            rho[r["stat"]].append(float(r["spearman_rho"]))
    n = A[0]["n_seeds"]
    lines = []
    for s, lab in stats:
        cells = []
        for c, _ in conds:
            r = get.get(("5.0", "1", s, c))
            cells.append(f3(r["auc_mean"]) if r else "--")
        rr = rho.get(s, [])
        cells.append(f"{sum(rr) / len(rr):.2f}" if rr else "--")
        lines.append(f"{lab} & " + " & ".join(cells) + " \\\\")
    head = " & ".join(l for _, l in conds)
    write("tab_detection.tex", f"""\\begin{{table*}}[t]
\\caption{{Single-Slot Detection AUC Against the Matched Condition at 5~dB and Rank Correlation
With the BLER Increase ({n} Training {seeds_word(n)}, {{\\nBlocksCond}} Test Slots per Condition)}}
\\label{{tab:detection}}
\\centering
\\footnotesize
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}l{'c' * len(conds)}c@{{}}}}
\\toprule
& \\multicolumn{{{len(conds)}}}{{c}}{{AUC (single slot)}} & Spearman \\\\
\\cmidrule(lr){{2-{len(conds) + 1}}}
Statistic & {head} & $\\rho$ \\\\
\\midrule
{chr(10).join(lines)}
\\bottomrule
\\end{{tabular}}
\\end{{table*}}
""")


# ------------------------------------------------------------------ Table: ablation
def tab_ablation():
    rows = read(os.path.join(DATA, "ablation_all.csv"))
    if not rows:
        return
    variants = [("full", "Full (reference)", "--"),
                ("no_pilot", "No pilot reference", "Is the LS input needed?"),
                ("pure_vfe", "Pure VFE (no BCE)", "Can the likelihood alone train detection?"),
                ("no_detach", "No stop-gradient", "Should the VFE shape the backbone?"),
                ("no_freeze", "No noise freeze", "Is the warm-up needed?")]
    bler = defaultdict(list); shift = defaultdict(list); seeds = defaultdict(set)
    for r in rows:
        if r["kind"] == "bler":
            bler[(r["variant"], float(r["snr_db"]))].append(float(r["bler"]))
        elif r["kind"] == "shift":
            shift[(r["variant"], r["cond"])].append(float(r["bler"]))
        seeds[r["variant"]].add(r["seed"])

    def m(v):
        return f"{sum(v) / len(v):.3f}" if v else "--"
    lines = []
    for v, lab, q in variants:
        if not seeds.get(v):
            continue
        cells = [m(bler[(v, 1.0)]), m(bler[(v, 3.0)]), m(shift[(v, "S1")]), m(shift[(v, "DS1000")]),
                 m(shift[(v, "S2")]), m(shift[(v, "V250")]), str(len(seeds[v]))]
        lines.append(f"{lab} & " + " & ".join(cells) + " \\\\")
    write("tab_ablation.tex", """\\begin{table*}[t]
\\caption{Ablation of the Training Design (Retrained From Scratch for $1.2\\times10^{4}$ Steps;
1280 Blocks per Entry; Mean Over Seeds)}
\\label{tab:ablation}
\\centering
\\footnotesize
\\setlength{\\tabcolsep}{4pt}
\\begin{tabular}{@{}lccccccc@{}}
\\toprule
& \\multicolumn{2}{c}{Matched BLER} & \\multicolumn{4}{c}{BLER at 5~dB under shift} & \\\\
\\cmidrule(lr){2-3}\\cmidrule(lr){4-7}
Variant & 1~dB & 3~dB & S1 & DS\\,1000 & S2 & 250\\,km/h & Seeds \\\\
\\midrule
""" + "\n".join(lines) + """
\\bottomrule
\\end{tabular}
\\end{table*}
""")


