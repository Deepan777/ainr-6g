def tab_adapt():
    rows = read(os.path.join(DATA, "adapt_summary.csv"))
    if not rows:
        return
    order = ["none", "ungated", "gated", "trig"]
    lab = {"none": "None", "ungated": "Ungated", "gated": "CRC-gated", "trig": "Triggered + CRC"}
    by = {(r["snr_db"], r["receiver"], r["mode"]): r for r in rows}
    lines = []
    for snr in ("3.0", "5.0"):
        for rx in ("AINR", "DiscNRX"):
            for i, md in enumerate(order):
                r = by.get((snr, rx, md))
                if not r:
                    continue
                pre = (f"\\multirow{{4}}{{*}}{{{float(snr):g}~dB}} & \\multirow{{4}}{{*}}{{{rx}}}" if (rx == "AINR" and i == 0)
                       else (f" & \\multirow{{4}}{{*}}{{{rx}}}" if i == 0 else " & "))
                if rx == "DiscNRX" and i == 0:
                    pre = f" & \\multirow{{4}}{{*}}{{{rx}}}"
                # One recovery slot per seed. Listing them all made the column grow with the
                # seed count (and overflow the text block), so report how many runs recovered
                # and the median slot among them; the per-seed slots stay in data/adapt_summary*.csv.
                import statistics as _st
                rec = r["recovery_slots"].split()
                done = [float(x) for x in rec if x != "inf"]
                if not done:
                    recs = "never"
                elif len(done) == len(rec):
                    recs = f"all ({_st.median(done):.0f})"
                else:
                    recs = f"{len(done)}/{len(rec)} ({_st.median(done):.0f})"
                ms = "--" if r["median_update_ms"] in ("", "nan") else f"{float(r['median_update_ms']):.0f}"
                lines.append(f"{pre} & {lab[md]} & {f3(r['first200'])} & {f3(r['last200'])} & "
                             f"{float(r['accepted_updates']):.0f} & {float(r['false_pass_updates']):.0f} & {recs} & {ms} \\\\")
            lines.append("\\cmidrule(l){2-9}" if rx == "AINR" else "\\midrule")
    lines[-1] = ""
    n = rows[0]["n_seeds"]
    write("tab_adapt.tex", f"""\\begin{{table*}}[t]
\\caption{{Online Adaptation After the S2 Shift With a Receiver-Side CRC16 (1000 Slots per Run;
Mean Over {n} Training {seeds_word(n)}, Including Runs Whose CRC Pass Rate Was Zero and Which
Therefore Never Adapt; Recovery Column: Runs That Recovered Out of All Runs, With the Median
Recovery Slot in Parentheses; Update Latency Measured During the Run)}}
\\label{{tab:adapt}}
\\centering
\\footnotesize
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}lllcccccc@{{}}}}
\\toprule
SNR & Receiver & Mode & BLER, slots 1--200 & BLER, slots 801--1000 & Updates & False-pass updates & Recovery slot & Update (ms) \\\\
\\midrule
{chr(10).join(l for l in lines if l)}
\\bottomrule
\\end{{tabular}}
\\end{{table*}}
""")


def tab_matched():
    cr = read(os.path.join(DATA, "matched_snr01.csv"))
    if not cr:
        return False
    import statistics
    lines = []
    for qam in ("16", "64"):
        rxs = [r for r in ("AINR", "DiscNRX", "LS-LIN", "LS-LMMSE", "PCSI") if any(c["qam"] == qam and c["receiver"] == r for c in cr)]
        for i, rx in enumerate(rxs):
            v = [float(c["snr_at_bler_0p1"]) for c in cr if c["qam"] == qam and c["receiver"] == rx]
            v = [x for x in v if x == x]
            n = len([c for c in cr if c["qam"] == qam and c["receiver"] == rx])
            if not v:
                cell = "not reached"
            elif len(v) > 1:
                import math as _m
                from scipy import stats as _st
                h = _st.t.ppf(0.975, len(v) - 1) * statistics.stdev(v) / _m.sqrt(len(v))
                cell = f"{statistics.mean(v):.2f} $\\pm$ {h:.2f}"
            else:
                cell = f"{v[0]:.2f}"
            seeds = "--" if rx.startswith(("LS", "PC")) else str(n)
            q = f"\\multirow{{{len(rxs)}}}{{*}}{{{qam}-QAM}}" if i == 0 else ""
            lines.append(f"{q} & {rx} & {cell} & {seeds} \\\\")
        lines.append("\\midrule")
    lines = lines[:-1]
    write("tab_matched.tex", """\\begin{table}[t]
\\caption{SNR (dB) at BLER $=0.1$ on the Matched Channel (Mean $\\pm$ 95\\% Interval Over Training Seeds)}
\\label{tab:matched}
\\centering
\\footnotesize
\\begin{tabular}{@{}llcc@{}}
\\toprule
Modulation & Receiver & SNR at BLER $=0.1$ & Seeds \\\\
\\midrule
""" + "\n".join(lines) + """
\\bottomrule
\\end{tabular}
\\end{table}
""")
    return True


