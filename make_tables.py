def tab_complexity():
    c = read(os.path.join(RES, "complexity.csv"))
    if not c:
        return False
    def med(stage, rx, b):
        for r in c:
            if r["stage"] == stage and r["receiver"] == rx and r.get("batch") in (str(b), f"{b}.0"):
                return float(r["median_ms"])
        return float("nan")
    st = {r["receiver"]: r for r in c if r["stage"] == "static"}
    rows = [("AINR detection", med("detection", "AINR", 1), med("detection", "AINR", 32), st.get("AINR", {}).get("params", ""), st.get("AINR", {}).get("macs_per_slot", "")),
            ("DiscNRX detection", med("detection", "DiscNRX", 1), med("detection", "DiscNRX", 32), st.get("DiscNRX", {}).get("params", ""), st.get("DiscNRX", {}).get("macs_per_slot", "")),
            ("LS-LIN detection", med("detection", "LS-LIN", 1), med("detection", "LS-LIN", 32), "--", "--"),
            ("LS-LMMSE detection", med("detection", "LS-LMMSE", 1), med("detection", "LS-LMMSE", 32), "--", "--"),
            ("of which CNN (AINR)", med("cnn", "AINR", 1), med("cnn", "AINR", 32), "", ""),
            ("of which LDPC BP", med("ldpc", "shared", 1), med("ldpc", "shared", 32), "", ""),
            ("Monitor, $S=1$", med("monitor", "AINR S=1", 1), med("monitor", "AINR S=1", 32), "", ""),
            ("Monitor, $S=4$", med("monitor", "AINR S=4", 1), med("monitor", "AINR S=4", 32), "", ""),
            ("CRC16 check", med("crc", "shared", 1), med("crc", "shared", 32), "", ""),
            ("Adaptation step, AINR", med("adapt", "AINR", 1), float("nan"), "", ""),
            ("Adaptation step, DiscNRX", med("adapt", "DiscNRX", 1), float("nan"), "", "")]
    def ms(x):
        return "--" if x != x else f"{x:.1f}"
    def big(x):
        try:
            v = float(x)
            e = int(math.floor(math.log10(v)))
            return f"${v / 10 ** e:.2f}\\times10^{{{e}}}$"
        except (TypeError, ValueError):
            return x
    lines = [f"{a} & {ms(b)} & {ms(c_)} & {big(d)} & {big(e)} \\\\" for a, b, c_, d, e in rows]
    write("tab_complexity.tex", """\\begin{table}[t]
\\caption{Complexity and Latency (Median of 50 CUDA-Synchronized Calls, GPU Otherwise Idle)}
\\label{tab:complexity}
\\centering
\\footnotesize
\\setlength{\\tabcolsep}{2pt}
\\begin{tabular}{@{}lcccc@{}}
\\toprule
Stage & $B{=}1$ & $B{=}32$ & Params & MACs \\\\
 & (ms) & (ms) & & (per slot) \\\\
\\midrule
""" + "\n".join(lines) + """
\\bottomrule
\\end{tabular}
\\end{table}
""")
    return True


